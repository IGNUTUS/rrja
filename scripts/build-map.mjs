/**
 * Builds the dot-matrix Philippines map used in the "Regional Coverage" section.
 * Source: Natural Earth 1:10m Admin 0 countries (public domain), https://www.naturalearthdata.com/
 *
 * Usage: node scripts/build-map.mjs <path-to-ne_10m_admin_0_countries.geojson>
 * Output: src/data/phMapDots.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'

const src = process.argv[2]
if (!src) throw new Error('Pass the path to the Natural Earth GeoJSON file')
const geo = JSON.parse(readFileSync(src, 'utf8'))
const ph = geo.features.find((f) => f.properties.ADM0_A3 === 'PHL' || f.properties.ISO_A3 === 'PHL')
const polys = ph.geometry.type === 'Polygon' ? [ph.geometry.coordinates] : ph.geometry.coordinates

const inRing = (x, y, ring) => {
  let inside = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j]
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside
  }
  return inside
}
const onLand = (x, y) => polys.some((p) => inRing(x, y, p[0]) && !p.slice(1).some((h) => inRing(x, y, h)))

// Island-group classification (approximate, good enough for a stylised illustration)
const group = (lon, lat) => {
  const palawan = lon < 120.4 && lat > 7.5
  if (palawan) return 'L'
  const masbate = lon > 123.1 && lon < 124.15 && lat > 11.75 && lat < 12.7
  if (masbate) return 'L'
  const mindanao = lat < 8.8 || (lon > 125.2 && lat < 10.55) || (lat < 9.45 && lon > 124.0)
  if (mindanao) return 'M'
  const samar = lon > 124.15 && lat < 12.7
  if ((lat < 12.0 && lon > 121.75) || samar) return 'V'
  return 'L'
}

const STEP = 0.17
const W0 = 116.8, N0 = 21.2, E0 = 126.7, S0 = 4.5
const dots = []
for (let lat = N0; lat >= S0; lat -= STEP) {
  for (let lon = W0; lon <= E0; lon += STEP) {
    let hit = false
    for (const dx of [-0.33, 0, 0.33]) for (const dy of [-0.33, 0, 0.33]) {
      if (!hit && onLand(lon + dx * STEP, lat + dy * STEP)) hit = true
    }
    if (hit) dots.push([Math.round((lon - W0) / STEP), Math.round((N0 - lat) / STEP), group(lon, lat)])
  }
}
const cols = Math.round((E0 - W0) / STEP) + 1
const rows = Math.round((N0 - S0) / STEP) + 1
const out = `// Generated by scripts/build-map.mjs from Natural Earth (public domain). Do not edit by hand.
// Each dot: [column, row, group] where group L = Luzon, V = Visayas, M = Mindanao.
export const PH_GRID = { cols: ${cols}, rows: ${rows}, step: ${STEP}, west: ${W0}, north: ${N0} } as const
export const PH_DOTS: ReadonlyArray<readonly [number, number, 'L' | 'V' | 'M']> = ${JSON.stringify(dots)}
`
writeFileSync(new URL('../src/data/phMapDots.ts', import.meta.url), out)
console.log(`dots: ${dots.length} (L ${dots.filter((d) => d[2] === 'L').length}, V ${dots.filter((d) => d[2] === 'V').length}, M ${dots.filter((d) => d[2] === 'M').length})`)
